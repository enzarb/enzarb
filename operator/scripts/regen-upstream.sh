#!/usr/bin/env bash
# Regenerate the committed kopium types in crates/enzarb-crds/src/upstream.
# Requires: kopium (cargo install kopium --version 0.24.1), curl, rustfmt.
set -euo pipefail
cd "$(dirname "$0")/.."

# agent-sandbox: ADR-0002 pins v0.5.x. Latest v0.5 patch release is v0.5.6
# (v1.0.x exists upstream but is outside the pinned line). v0.5.6 serves
# agents.x-k8s.io/v1beta1 for Sandbox.
AGENT_SANDBOX_VERSION=v0.5.6
AGENT_SANDBOX_URL="https://raw.githubusercontent.com/kubernetes-sigs/agent-sandbox/${AGENT_SANDBOX_VERSION}/k8s/crds/agents.x-k8s.io_sandboxes.yaml"

out=crates/enzarb-crds/src/upstream
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

gen() { # name url version api-version
  curl -fsSL "$2" -o "$tmp/$1.yaml"
  {
    echo "// @generated by scripts/regen-upstream.sh from $2"
    echo "// Upstream $1 CRD at $3 (api version $4). Do not edit by hand."
    echo "#![allow(clippy::all, unused_imports)]"
    kopium -f "$tmp/$1.yaml" --api-version "$4" --docs --derive Default --derive PartialEq --smart-derive-elision
  } > "$out/$1.rs"
  rustfmt --edition 2024 "$out/$1.rs"
}

gen sandbox "$AGENT_SANDBOX_URL" "$AGENT_SANDBOX_VERSION" v1beta1
