#!/usr/bin/env bash
# Regenerate the vendored bases (capsule, capsule-proxy, pgop) from their Helm
# charts using the versions in hack/versions.env. Requires: helm.
# Helm hook Jobs (CRD-lifecycle/post-install/pre-delete) are disabled; CRDs are
# vendored statically in <base>/crds so they can be applied and awaited first.
set -euo pipefail
cd "$(dirname "$0")/.."
# shellcheck source=versions.env
source hack/versions.env

helm repo add projectcapsule https://projectcapsule.github.io/charts >/dev/null 2>&1 || true
helm repo update projectcapsule >/dev/null

vendor() { # name chart-ref version namespace [helm args...]
  local name=$1 chart=$2 version=$3 ns=$4; shift 4
  local dir=base/$name
  rm -rf "$dir"; mkdir -p "$dir"
  local hdr="# GENERATED by hack/refresh-vendored.sh: $chart $version"
  local res=()

  if [ "${WITH_CRDS:-1}" = 1 ]; then
    mkdir -p "$dir/crds"
    helm show crds "$chart" --version "$version" > "$dir/crds/crds.yaml"
    printf '%s\napiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - crds.yaml\n' \
      "$hdr" > "$dir/crds/kustomization.yaml"
    res+=("crds")
  fi
  if [ "${NS_OWNER:-1}" = 1 ]; then
    printf 'apiVersion: v1\nkind: Namespace\nmetadata:\n  name: %s\n' "$ns" > "$dir/namespace.yaml"
    res+=("namespace.yaml")
  fi
  helm template "$name" "$chart" --version "$version" -n "$ns" --skip-crds "$@" > "$dir/$name.yaml"
  res+=("$name.yaml")

  {
    echo "$hdr"
    echo "# Bump: edit hack/versions.env, run hack/refresh-vendored.sh, review the diff."
    printf 'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n'
    printf '  - %s\n' "${res[@]}"
  } > "$dir/kustomization.yaml"
}

jobs_off=(--set crds.install=false --set global.jobs.postInstall.enabled=false --set global.jobs.preDelete.enabled=false)

vendor capsule projectcapsule/capsule "$CAPSULE_CHART_VERSION" capsule-system "${jobs_off[@]}"
# capsule-proxy shares the capsule-system namespace and the proxy CRDs (bundled in
# the capsule chart) owned by base/capsule, so apply it after base/capsule.
NS_OWNER=0 WITH_CRDS=0 vendor capsule-proxy projectcapsule/capsule-proxy "$CAPSULE_PROXY_CHART_VERSION" capsule-system --set crds.install=false
vendor pgop oci://ghcr.io/ruckc/charts/pgop "$PGOP_CHART_VERSION" pgop-system
