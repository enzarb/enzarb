    #[test]
    fn a_recent_shared_target_goes_unless_a_build_holds_its_lock() {
        use nix::fcntl::{Flock, FlockArg};
        let t = tempfile::tempdir().unwrap();
        let ws = t.path();
        let (free, held) = (
            ws.join(".cache/target/o/free"),
            ws.join(".cache/target/o/held"),
        );
        for d in [&free, &held] {
            tag(d);
            std::fs::create_dir_all(d.join("debug")).unwrap();
            std::fs::write(d.join("debug/.cargo-lock"), "").unwrap();
        }
        let lock = Flock::lock(
            std::fs::File::open(held.join("debug/.cargo-lock")).unwrap(),
            FlockArg::LockExclusiveNonblock,
        )
        .unwrap();
        // The repo of a running step is not special: only the lock counts.
        let never = ws.join("never-removed");
        std::fs::write(&never, "").unwrap();
        let fake = Fake {
            busy: ["any".to_string()].into(),
            ..Fake::default()
        };
        assert_eq!(pass(ws, &fake, &never), 1);
        assert!(!free.exists() && held.exists());
        drop(lock);
        assert_eq!(pass(ws, &fake, &never), 1);
        assert!(!held.exists());
    }

    #[test]
    fn sccache_is_trimmed_oldest_first_without_following_links() {
        let t = tempfile::tempdir().unwrap();
        let ws = t.path();
        let sc = ws.join(".cache/sccache");
        std::fs::create_dir_all(sc.join("a")).unwrap();
        let outside = ws.join("outside");
        std::fs::write(&outside, "keep").unwrap();
        std::os::unix::fs::symlink(&outside, sc.join("a/link")).unwrap();
        let now = SystemTime::now();
        for (name, age) in [("a/old", 300u64), ("a/mid", 200), ("a/new", 100)] {
            std::fs::write(sc.join(name), "x").unwrap();
            std::fs::File::open(sc.join(name))
                .unwrap()
                .set_modified(now - Duration::from_secs(age))
                .unwrap();
        }
        let left = || {
            ["a/old", "a/mid", "a/new"]
                .iter()
                .filter(|n| sc.join(n).exists())
                .count()
        };
        // Low while more than one file is left: the two oldest go.
        let n = prune_sccache(ws, &|| left() > 1, &|| false);
        assert_eq!(n, 2);
        assert!(sc.join("a/new").exists());
        assert!(
            outside.exists() && sc.join("a/link").exists(),
            "links are not followed"
        );
        // Not low: untouched.
        assert_eq!(prune_sccache(ws, &|| false, &|| false), 0);
    }

