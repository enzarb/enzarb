    #[derive(Default)]
    struct Fake {
        busy: HashSet<String>,
        protected: HashSet<String>,
    }

    impl Registry for Fake {
        fn with_busy_tasks(&self, f: &mut dyn FnMut(&HashSet<String>)) {
            f(&self.busy)
        }

        fn with_protected_tasks(&self, f: &mut dyn FnMut(&HashSet<String>)) {
            f(&self.protected)
        }
    }

    fn git_in(dir: &Path, args: &[&str]) {
        let out = std::process::Command::new("git")
            .args(["-c", "user.name=t", "-c", "user.email=t@t"])
            .args(["-c", "protocol.file.allow=always"])
            .args(args)
            .current_dir(dir)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }

    /// `tasks/<task>/o/r` with a tagged `target/`, a source file and a commit that is on no
    /// remote (`pushed` = false) or on a bare `origin` (true).
    fn checkout(ws: &Path, task: &str, pushed: bool) -> PathBuf {
        let repo = ws.join("tasks").join(task).join("o/r");
        std::fs::create_dir_all(&repo).unwrap();
        git_in(&repo, &["init", "-q", "-b", "main"]);
        std::fs::write(repo.join("src.rs"), "fn main() {}\n").unwrap();
        git_in(&repo, &["add", "."]);
        git_in(&repo, &["commit", "-q", "-m", "x"]);
        if pushed {
            let bare = ws.join(format!("remote-{task}.git"));
            git_in(ws, &["init", "-q", "--bare", bare.to_str().unwrap()]);
            git_in(&repo, &["remote", "add", "origin", bare.to_str().unwrap()]);
            git_in(&repo, &["push", "-q", "origin", "main"]);
        }
        tag(&repo.join("target"));
        repo
    }

    /// Runs a pass whose `low()` holds while `until` exists.
    fn pass(ws: &Path, reg: &Fake, until: &Path) -> usize {
        prune_pass(ws, reg, &|| until.exists(), &|| false, 20)
    }

    #[test]
    fn stops_after_the_cheapest_phase_that_is_enough() {
        let t = tempfile::tempdir().unwrap();
        let ws = t.path();
        let old = checkout(ws, "old", true);
        tag(&ws.join(".cache/target/o/r"));
        std::fs::create_dir_all(ws.join(".cache/sccache")).unwrap();
        std::fs::write(ws.join(".cache/sccache/f"), "x").unwrap();
        // Low until the first task's cache is gone: later phases are not touched.
        assert_eq!(pass(ws, &Fake::default(), &old.join("target")), 1);
        assert!(old.join("src.rs").exists());
        assert!(ws.join(".cache/sccache/f").exists());
        assert!(ws.join(".cache/target/o/r").exists());
    }

    #[test]
    fn phases_run_in_order_caches_checkouts_sccache_targets() {
        let t = tempfile::tempdir().unwrap();
        let ws = t.path();
        let a = checkout(ws, "a", true);
        let target = ws.join(".cache/target/o/r");
        tag(&target);
        std::fs::create_dir_all(ws.join(".cache/sccache/x")).unwrap();
        std::fs::write(ws.join(".cache/sccache/x/f"), "x").unwrap();
        // Needs the checkout gone: the cache goes first, then the checkout, sccache stays.
        let fake = Fake::default();
        let n = pass(ws, &fake, &ws.join("tasks/a"));
        assert_eq!(n, 2);
        assert!(!ws.join("tasks/a").exists() && !a.exists());
        assert!(ws.join(".cache/sccache/x/f").exists());
        assert!(target.exists());
        // Needs sccache trimmed: the file goes, the shared target stays.
        let sc = ws.join(".cache/sccache/x/f");
        let n = pass(ws, &fake, &sc);
        assert_eq!(n, 1);
        assert!(target.exists());
        // Needs the shared target gone.
        assert_eq!(pass(ws, &fake, &target), 1);
        assert!(!target.exists());
    }

    #[test]
    fn checkouts_go_oldest_first_and_only_as_many_as_needed() {
        let t = tempfile::tempdir().unwrap();
        let ws = t.path();
        let (a, b) = (checkout(ws, "a", true), checkout(ws, "b", true));
        for r in [&a, &b] {
            std::fs::remove_dir_all(r.join("target")).unwrap(); // no cache phase
        }
        // `a` was used last, `b` long ago (the age is that of the directories).
        for (task, age) in [("a", 60u64), ("b", 7200)] {
            let when = SystemTime::now() - Duration::from_secs(age);
            let task = ws.join("tasks").join(task);
            for d in [task.join("o/r"), task.join("o"), task.clone()] {
                std::fs::File::open(&d).unwrap().set_modified(when).unwrap();
            }
        }
        // Low until `b` is gone: `a` stays.
        assert_eq!(pass(ws, &Fake::default(), &ws.join("tasks/b")), 1);
        assert!(!ws.join("tasks/b").exists() && ws.join("tasks/a").exists());
        assert!(
            std::fs::read_dir(ws.join("tasks"))
                .unwrap()
                .flatten()
                .all(|e| !is_aside(&e.path())),
            "nothing left aside"
        );
    }

