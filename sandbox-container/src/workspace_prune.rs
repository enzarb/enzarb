//! Automatic pruning of the workspace PVC.
//!
//! Nothing else deletes what steps leave in `<ws>/tasks/<task_id>/`, and build output (a Cargo
//! `target/` is several GB) fills the workspace PVC. When the periodic check (or a step about
//! to start) finds less than `ENZARB_WORKSPACE_PRUNE_MIN_FREE` percent free, the
//! [`WorkspacePruner`] frees space in phases, cheapest loss first, and stops as soon as enough
//! is free:
//!
//! 1. cache directories (those holding a valid `CACHEDIR.TAG`, <https://bford.info/cachedir/>;
//!    Cargo writes one in `target/`) of tasks with no running step, least recently used first;
//! 2. whole `tasks/<id>/` checkouts of tasks that ended (no running or resumable run), oldest
//!    first, unless they hold commits that are on no remote;
//! 3. the sccache directory, oldest files first;
//! 4. the per-repo shared Cargo target dirs (`<ws>/.cache/target/<owner>/<repo>`), unless a
//!    build holds the Cargo lock.
//!
//! All of it is regenerated by the next build or clone. A directory is first renamed aside
//! while the step registry is locked, so a step that starts afterwards never sees half of one.
//! Best-effort: failures are logged.

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, SystemTime};

use tokio_util::sync::CancellationToken;

use crate::docker_prune::disk_usage;
use crate::steps::StepManager;

pub const DEFAULT_MIN_FREE_PERCENT: u8 = 20;
pub const CHECK_INTERVAL: Duration = Duration::from_secs(5 * 60);
/// How deep under a task directory cache directories are looked for.
const MAX_DEPTH: usize = 5;
const TAG: &str = "CACHEDIR.TAG";
const SIGNATURE: &[u8] = b"Signature: 8a477f597d28d172789f06886806bc55";
/// Suffix of a cache renamed aside next to where it was, waiting for deletion. Renaming within
/// its own directory needs no new directory, so it works on a full disk; a leftover (a crash
/// mid-delete) still holds its tag and is found again by the next pass.
const ASIDE: &str = ".enzarb-prune-";

#[derive(Debug, Clone)]
pub struct WorkspacePruneConfig {
    /// `ENZARB_WORKSPACE_PRUNE=off` disables it (default on).
    pub enabled: bool,
    /// `ENZARB_WORKSPACE_PRUNE_MIN_FREE`: percent of the workspace that must stay free (1..=99).
    pub min_free_percent: u8,
    pub interval: Duration,
}

impl Default for WorkspacePruneConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            min_free_percent: DEFAULT_MIN_FREE_PERCENT,
            interval: CHECK_INTERVAL,
        }
    }
}

impl WorkspacePruneConfig {
    pub fn from_lookup(get: impl Fn(&str) -> Option<String>) -> anyhow::Result<Self> {
        let mut c = Self::default();
        if let Some(v) = get("ENZARB_WORKSPACE_PRUNE") {
            c.enabled = match v.trim().to_ascii_lowercase().as_str() {
                "" | "1" | "true" | "yes" | "on" => true,
                "0" | "false" | "no" | "off" => false,
                _ => anyhow::bail!("ENZARB_WORKSPACE_PRUNE: must be on or off"),
            };
        }
        if let Some(v) = get("ENZARB_WORKSPACE_PRUNE_MIN_FREE").filter(|s| !s.trim().is_empty()) {
            let n: Option<u8> = v.trim().trim_end_matches('%').trim().parse().ok();
            c.min_free_percent = n.filter(|n| (1..=99).contains(n)).ok_or_else(|| {
                anyhow::anyhow!(
                    "ENZARB_WORKSPACE_PRUNE_MIN_FREE={v:?}: must be a percentage from 1 to 99, such as 20%"
                )
            })?;
        }
        Ok(c)
    }
}

pub struct WorkspacePruner {
    cfg: WorkspacePruneConfig,
    workspace: PathBuf,
    steps: StepManager,
}

impl WorkspacePruner {
    pub fn new(cfg: WorkspacePruneConfig, workspace: PathBuf, steps: StepManager) -> Self {
        Self {
            cfg,
            workspace,
            steps,
        }
    }

    pub fn spawn(self, stop: CancellationToken) -> tokio::task::JoinHandle<()> {
        tokio::spawn(async move {
            if !self.cfg.enabled {
                return;
            }
            loop {
                let ws = self.workspace.clone();
                let steps = self.steps.clone();
                let min = self.cfg.min_free_percent;
                let stop2 = stop.clone();
                let _ = tokio::task::spawn_blocking(move || {
                    prune_once_until(&ws, &steps, min, &|| stop2.is_cancelled())
                })
                .await;
                tokio::select! {
                    _ = stop.cancelled() => return,
                    _ = tokio::time::sleep(self.cfg.interval) => {}
                }
            }
        })
    }
}

/// What a pass needs from the step registry (a trait so tests can fake it).
pub trait Registry {
    /// Calls `f` with the tasks that have a running step, while no step can start or end.
    fn with_busy_tasks(&self, f: &mut dyn FnMut(&HashSet<String>));
    /// Calls `f` with the tasks whose checkout must stay (running or resumable), while no step
    /// can start or end.
    fn with_protected_tasks(&self, f: &mut dyn FnMut(&HashSet<String>));
}

impl Registry for StepManager {
    fn with_busy_tasks(&self, f: &mut dyn FnMut(&HashSet<String>)) {
        StepManager::with_busy_tasks(self, |s| f(s))
    }

    fn with_protected_tasks(&self, f: &mut dyn FnMut(&HashSet<String>)) {
        StepManager::with_protected_tasks(self, |s| f(s))
    }
}

/// One pass: returns the number of entries removed (cache directories, checkouts, sccache
/// files, shared target directories).
pub fn prune_once(workspace: &Path, steps: &StepManager, min_free_percent: u8) -> usize {
    prune_once_until(workspace, steps, min_free_percent, &|| false)
}

/// Unique names for renamed-aside caches.
static SEQ: AtomicU64 = AtomicU64::new(0);

fn prune_once_until(
    workspace: &Path,
    steps: &StepManager,
    min_free_percent: u8,
    stopped: &dyn Fn() -> bool,
) -> usize {
    // One pass at a time: the periodic one and the one before a step starts.
    let _pass = steps.prune_lock();
    let low = || disk_usage(workspace).is_some_and(|d| d.is_low(min_free_percent));
    prune_pass(workspace, steps, &low, stopped, min_free_percent)
}

/// A checkout kept because its commits may exist nowhere else: the repository and how many
/// commits are on no remote (`None`: could not be determined).
type Skipped = (PathBuf, Option<u64>);

/// The phases, cheapest loss first; each one runs only while `low()` holds.
fn prune_pass(
    workspace: &Path,
    steps: &dyn Registry,
    low: &dyn Fn() -> bool,
    stopped: &dyn Fn() -> bool,
    min_free_percent: u8,
) -> usize {
    if !low() {
        return 0;
    }
    let mut removed = sweep_leftovers(workspace);
    let mut skipped: Vec<Skipped> = Vec::new();
    if low() && !stopped() {
        removed += prune_task_caches(workspace, steps, low, stopped);
    }
    if low() && !stopped() {
        removed += prune_task_checkouts(workspace, steps, low, stopped, &mut skipped);
    }
    if low() && !stopped() {
        removed += prune_sccache(workspace, low, stopped);
    }
    if low() && !stopped() {
        removed += prune_shared_targets(workspace, low, stopped);
    }
    if low() && !stopped() {
        let top = breakdown(workspace, BREAKDOWN_TOP);
        let fmt = |v: &[(String, u64)]| {
            v.iter()
                .map(|(n, b)| format!("{n}={}MiB", b / (1024 * 1024)))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let kept = skipped
            .iter()
            .map(|(p, n)| match n {
                Some(n) => format!("{} ({n} unpushed commits)", p.display()),
                None => format!("{} (unpushed commits unknown)", p.display()),
            })
            .collect::<Vec<_>>()
            .join(", ");
        tracing::warn!(
            min_free_percent,
            removed,
            largest = %fmt(&top),
            kept_for_unpushed_work = %kept,
            "low_disk: workspace still short of free space after pruning; the largest top-level entries are not pruned automatically"
        );
    }
    removed
}

/// Removes what an earlier pass renamed aside and did not finish deleting (a crash
/// mid-delete), also when its tag is already gone.
fn sweep_leftovers(workspace: &Path) -> usize {
    let mut n = 0;
    let found = leftovers(&workspace.join("tasks"), MAX_DEPTH + 1)
        .into_iter()
        .chain(leftovers(&workspace.join(".cache/target"), 3));
    for p in found {
        match std::fs::remove_dir_all(&p) {
            Ok(()) => n += 1,
            Err(e) => {
                tracing::warn!(path = %p.display(), error = %e, "could not remove a leftover pruned directory")
            }
        }
    }
    n
}

/// Directories named like an [`ASIDE`] leftover under `root` (not following symlinks, not
/// inside `.git` or inside a leftover).
fn leftovers(root: &Path, depth: usize) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for e in std::fs::read_dir(root).into_iter().flatten().flatten() {
        if !e.file_type().is_ok_and(|t| t.is_dir()) || e.file_name() == ".git" {
            continue;
        }
        if is_aside(&e.path()) {
            out.push(e.path());
        } else if depth > 1 {
            out.extend(leftovers(&e.path(), depth - 1));
        }
    }
    out
}

fn is_aside(p: &Path) -> bool {
    p.file_name()
        .is_some_and(|f| f.to_string_lossy().contains(ASIDE))
}

/// Phase 1: tagged caches inside the task workspaces of idle tasks, least recently used first.
fn prune_task_caches(
    workspace: &Path,
    steps: &dyn Registry,
    low: &dyn Fn() -> bool,
    stopped: &dyn Fn() -> bool,
) -> usize {
    let mut removed = 0;
    for task in tasks_by_age(&workspace.join("tasks")) {
        if stopped() || !low() {
            break;
        }
        let caches: Vec<PathBuf> = cache_dirs(&task, MAX_DEPTH)
            .into_iter()
            .filter(|c| !tag_is_tracked(c))
            .collect();
        if caches.is_empty() {
            continue;
        }
        let name = task_name(&task);
        // Renamed aside while no step can start, then deleted outside the lock.
        let mut moved = Vec::new();
        steps.with_busy_tasks(&mut |busy| {
            if !busy.contains(&name) {
                moved = caches.iter().filter_map(|c| move_aside(c)).collect();
            }
        });
        for m in &moved {
            if let Err(e) = std::fs::remove_dir_all(m) {
                tracing::warn!(path = %m.display(), error = %e, "could not remove a pruned cache");
            }
        }
        if !moved.is_empty() {
            removed += moved.len();
            tracing::info!(task = %name, caches = moved.len(), "pruned task workspace caches");
        }
    }
    removed
}

fn task_name(task: &Path) -> String {
    task.file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default()
}

/// Phase 2: whole `tasks/<id>/` checkouts of tasks that ended, oldest first. A task stays if
/// any of its runs is running or can be resumed, and so does a checkout holding commits that
/// are on no remote (a chat can read an unpushed run branch from it, and can't push, so it may
/// be the only copy). The next step of the task clones again.
fn prune_task_checkouts(
    workspace: &Path,
    steps: &dyn Registry,
    low: &dyn Fn() -> bool,
    stopped: &dyn Fn() -> bool,
    skipped: &mut Vec<Skipped>,
) -> usize {
    let mut removed = 0;
    for task in tasks_by_age(&workspace.join("tasks")) {
        if stopped() || !low() {
            break;
        }
        let name = task_name(&task);
        let mut protected = false;
        steps.with_protected_tasks(&mut |keep| protected = keep.contains(&name));
        if protected {
            continue;
        }
        let mut unsafe_to_delete = false;
        for repo in git_repos(&task, 3) {
            match unpushed_commits(&repo) {
                Ok(0) => {}
                Ok(n) => {
                    skipped.push((repo, Some(n)));
                    unsafe_to_delete = true;
                }
                Err(e) => {
                    tracing::warn!(repo = %repo.display(), error = %e, "cannot count unpushed commits; keeping the checkout");
                    skipped.push((repo, None));
                    unsafe_to_delete = true;
                }
            }
        }
        if unsafe_to_delete {
            continue;
        }
        // Renamed aside while no step can start; a step that registered meanwhile wins.
        let mut moved = None;
        steps.with_protected_tasks(&mut |keep| {
            if !keep.contains(&name) {
                moved = move_aside(&task);
            }
        });
        let Some(m) = moved else { continue };
        if let Err(e) = std::fs::remove_dir_all(&m) {
            tracing::warn!(path = %m.display(), error = %e, "could not remove a pruned task checkout");
        }
        removed += 1;
        tracing::info!(task = %name, "pruned the checkout of an ended task");
    }
    removed
}

/// Repositories (directories with a `.git`) at most `depth` levels under `dir`, `dir`
/// included; never into a repository or through a symlink.
fn git_repos(dir: &Path, depth: usize) -> Vec<PathBuf> {
    if std::fs::symlink_metadata(dir.join(".git")).is_ok() {
        return vec![dir.to_path_buf()];
    }
    if depth == 0 {
        return Vec::new();
    }
    std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
        .flat_map(|e| git_repos(&e.path(), depth - 1))
        .collect()
}

/// Commits of local branches that are on no remote-tracking branch.
fn unpushed_commits(repo: &Path) -> Result<u64, String> {
    let mut c = std::process::Command::new("git");
    c.args([
        "-c",
        "safe.directory=*",
        "rev-list",
        "--count",
        "--branches",
        "--not",
        "--remotes",
    ])
    .current_dir(repo);
    crate::privs::as_sandbox_user(&mut c);
    let out = c.output().map_err(|e| e.to_string())?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).trim().to_string());
    }
    String::from_utf8_lossy(&out.stdout)
        .trim()
        .parse()
        .map_err(|e| format!("unexpected git output: {e}"))
}

/// Phase 3: the sccache directory, oldest files first. Deleting under a live sccache server
/// only costs cache misses. Symlinks are never followed, nor other filesystems.
fn prune_sccache(workspace: &Path, low: &dyn Fn() -> bool, stopped: &dyn Fn() -> bool) -> usize {
    use std::os::unix::fs::MetadataExt;
    fn collect(p: &Path, dev: u64, out: &mut Vec<(SystemTime, PathBuf)>) {
        for e in std::fs::read_dir(p).into_iter().flatten().flatten() {
            let Ok(m) = std::fs::symlink_metadata(e.path()) else {
                continue;
            };
            if m.dev() != dev {
                continue;
            }
            if m.is_dir() {
                collect(&e.path(), dev, out);
            } else if m.is_file() {
                out.push((m.modified().unwrap_or(SystemTime::UNIX_EPOCH), e.path()));
            }
        }
    }
    let root = workspace.join(".cache/sccache");
    let Ok(m) = std::fs::symlink_metadata(&root) else {
        return 0;
    };
    if !m.is_dir() {
        return 0;
    }
    let mut files = Vec::new();
    collect(&root, m.dev(), &mut files);
    files.sort();
    let mut removed = 0;
    for (_, f) in files {
        if stopped() || !low() {
            break;
        }
        if std::fs::remove_file(&f).is_ok() {
            removed += 1;
        }
    }
    if removed > 0 {
        tracing::info!(files = removed, "trimmed the sccache directory");
    }
    removed
}

/// Whether a build holds the Cargo lock of the shared target dir
/// (`<dir>/<profile>/.cargo-lock`, flock). Removing the dir then would break that build; between
/// builds it only costs a rebuild.
fn build_lock_held(dir: &Path) -> bool {
    use nix::fcntl::{Flock, FlockArg};
    for e in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        let lock = e.path().join(".cargo-lock");
        let Ok(f) = std::fs::File::open(&lock) else {
            continue;
        };
        match Flock::lock(f, FlockArg::LockExclusiveNonblock) {
            Ok(_) => {} // unlocks on drop
            Err(_) => return true,
        }
    }
    false
}

/// Phase 4: the per-repo shared Cargo target dirs `<ws>/.cache/target/<owner>/<repo>`, least
/// recently written first, except those a build holds the lock of.
fn prune_shared_targets(
    workspace: &Path,
    low: &dyn Fn() -> bool,
    stopped: &dyn Fn() -> bool,
) -> usize {
    let root = workspace.join(".cache/target");
    let mut dirs: Vec<(SystemTime, PathBuf)> = cache_dirs(&root, 2)
        .into_iter()
        .map(|d| (newest(&d, 2), d))
        .collect();
    dirs.sort();
    let mut removed = 0;
    for (_, d) in dirs {
        if stopped() || !low() {
            break;
        }
        if build_lock_held(&d) {
            continue;
        }
        let Some(m) = move_aside(&d) else { continue };
        if let Err(e) = std::fs::remove_dir_all(&m) {
            tracing::warn!(path = %m.display(), error = %e, "could not remove a pruned shared target dir");
        }
        removed += 1;
        tracing::info!(dir = %d.display(), "pruned a shared target dir");
    }
    removed
}

/// How many entries the `low_disk` warning lists.
const BREAKDOWN_TOP: usize = 8;

/// Disk use of `tasks/*` and `.cache/*` (relative names), largest first, at most `top` entries.
/// Best-effort; symlinks are counted as themselves, never followed.
fn breakdown(workspace: &Path, top: usize) -> Vec<(String, u64)> {
    let mut v = Vec::new();
    for group in ["tasks", ".cache"] {
        for e in std::fs::read_dir(workspace.join(group))
            .into_iter()
            .flatten()
            .flatten()
        {
            let name = format!("{group}/{}", e.file_name().to_string_lossy());
            v.push((name, disk_bytes(&e.path())));
        }
    }
    v.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    v.truncate(top);
    v
}

/// Allocated bytes under `p`, without following symlinks or crossing filesystems.
fn disk_bytes(p: &Path) -> u64 {
    use std::os::unix::fs::MetadataExt;
    fn walk(p: &Path, dev: u64) -> u64 {
        let Ok(m) = std::fs::symlink_metadata(p) else {
            return 0;
        };
        if m.dev() != dev {
            return 0;
        }
        let mut n = m.blocks() * 512;
        if m.is_dir() {
            for e in std::fs::read_dir(p).into_iter().flatten().flatten() {
                n += walk(&e.path(), dev);
            }
        }
        n
    }
    match std::fs::symlink_metadata(p) {
        Ok(m) => walk(p, m.dev()),
        Err(_) => 0,
    }
}

/// Renames a cache next to itself (see [`ASIDE`]); a cache already aside is returned as is.
fn move_aside(c: &Path) -> Option<PathBuf> {
    if c.file_name()
        .is_some_and(|f| f.to_string_lossy().contains(ASIDE))
    {
        return Some(c.to_path_buf());
    }
    let n = SEQ.fetch_add(1, Ordering::Relaxed);
    let base = c.file_name()?.to_string_lossy().into_owned();
    let to = c.with_file_name(format!(".{base}{ASIDE}{}-{n}", std::process::id()));
    match std::fs::rename(c, &to) {
        Ok(()) => Some(to),
        Err(e) => {
            tracing::warn!(path = %c.display(), error = %e, "could not move a cache aside");
            None
        }
    }
}

/// Task directories, least recently modified first (by their newest entry two levels down).
fn tasks_by_age(tasks: &Path) -> Vec<PathBuf> {
    let mut v: Vec<(SystemTime, PathBuf)> = std::fs::read_dir(tasks)
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_dir()))
        .filter(|e| !is_aside(&e.path()))
        .map(|e| (newest(&e.path(), 3), e.path()))
        .collect();
    v.sort();
    v.into_iter().map(|(_, p)| p).collect()
}

fn newest(dir: &Path, depth: usize) -> SystemTime {
    let mut t = mtime(dir);
    if depth == 0 {
        return t;
    }
    for e in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        if e.file_type().is_ok_and(|t| t.is_dir()) && e.file_name() != ".git" {
            t = t.max(newest(&e.path(), depth - 1));
        }
    }
    t
}

fn mtime(p: &Path) -> SystemTime {
    std::fs::symlink_metadata(p)
        .and_then(|m| m.modified())
        .unwrap_or(SystemTime::UNIX_EPOCH)
}

/// Directories under `root` (not following symlinks, not inside `.git` or another cache) that
/// hold a valid `CACHEDIR.TAG`.
pub fn cache_dirs(root: &Path, depth: usize) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for e in std::fs::read_dir(root).into_iter().flatten().flatten() {
        let Ok(t) = e.file_type() else { continue };
        if !t.is_dir() || e.file_name() == ".git" {
            continue;
        }
        let p = e.path();
        if is_cache(&p) {
            out.push(p);
        } else if depth > 1 {
            out.extend(cache_dirs(&p, depth - 1));
        }
    }
    out
}

/// A `CACHEDIR.TAG` committed to the repository marks tracked content, not a build cache.
fn tag_is_tracked(dir: &Path) -> bool {
    let mut c = std::process::Command::new("git");
    c.args(["-c", "safe.directory=*", "ls-files", "--error-unmatch", TAG])
        .current_dir(dir)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null());
    crate::privs::as_sandbox_user(&mut c);
    c.status().is_ok_and(|s| s.success())
}

fn is_cache(dir: &Path) -> bool {
    std::fs::read(dir.join(TAG)).is_ok_and(|b| b.starts_with(SIGNATURE))
}

