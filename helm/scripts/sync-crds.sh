#!/usr/bin/env bash
# Vendor the Project CRD from operator/ into the chart's crds/ directory.
# Usage: scripts/sync-crds.sh [path-to-project.yaml]
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
src="${1:-$here/../operator/deploy/crds/project.yaml}"
dst="$here/enzarb/crds/project.yaml"
[ -f "$src" ] || { echo "missing $src" >&2; exit 1; }
mkdir -p "$(dirname "$dst")"
{
  echo "# GENERATED by scripts/sync-crds.sh from operator/deploy/crds/project.yaml. Do not edit."
  cat "$src"
} > "$dst"
echo "wrote $dst"
