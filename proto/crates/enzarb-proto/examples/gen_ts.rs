//! Generates `ts/src/ctrl.gen.ts` from the Rust CTRL types: the TypeScript
//! types (ts-rs), the list of `type` tags and the table of secret fields
//! (schemars; secrets are the `Secret` newtype). Run `mise run proto:gen`
//! (or `cargo run -p enzarb-proto --features codegen --example gen_ts`); CI
//! fails when the committed file is stale.
//!
//! Usage: `gen_ts [OUT]` (default `ts/src/ctrl.gen.ts`; `-` writes to stdout).

use std::any::TypeId;
use std::collections::BTreeMap;
use std::fmt::Write as _;

use enzarb_proto::Ctrl;
use serde_json::Value;
use ts_rs::{Config, TS, TypeVisitor};

const DEFAULT_OUT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../ts/src/ctrl.gen.ts");

/// Collects the declaration of every type reachable from the visited one.
struct Decls<'a> {
    cfg: &'a Config,
    seen: Vec<TypeId>,
    decls: BTreeMap<String, String>,
}

impl TypeVisitor for Decls<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() || self.seen.contains(&TypeId::of::<T>()) {
            return;
        }
        self.seen.push(TypeId::of::<T>());
        self.decls.insert(T::ident(self.cfg), T::decl(self.cfg));
        T::visit_dependencies(self);
    }
}

/// Paths (`*` = any map value or array item) of the `x-secret` strings under `schema`.
fn secret_paths(
    schema: &Value,
    defs: &Value,
    path: &mut Vec<String>,
    out: &mut Vec<Vec<String>>,
    depth: usize,
) {
    let Some(obj) = schema.as_object() else {
        return;
    };
    if depth > 24 {
        panic!("schema nests too deeply at {path:?}");
    }
    if obj.get("x-secret") == Some(&Value::Bool(true)) {
        if !out.contains(path) {
            out.push(path.clone());
        }
        return;
    }
    if let Some(name) = obj
        .get("$ref")
        .and_then(Value::as_str)
        .and_then(|r| r.strip_prefix("#/$defs/"))
    {
        secret_paths(&defs[name], defs, path, out, depth + 1);
    }
    for key in ["anyOf", "oneOf", "allOf"] {
        for sub in obj.get(key).and_then(Value::as_array).into_iter().flatten() {
            secret_paths(sub, defs, path, out, depth + 1);
        }
    }
    for (name, sub) in obj
        .get("properties")
        .and_then(Value::as_object)
        .into_iter()
        .flatten()
    {
        path.push(name.clone());
        secret_paths(sub, defs, path, out, depth + 1);
        path.pop();
    }
    for key in ["additionalProperties", "items"] {
        if let Some(sub) = obj.get(key) {
            path.push("*".into());
            secret_paths(sub, defs, path, out, depth + 1);
            path.pop();
        }
    }
}

/// The `type` tag of one `Ctrl` variant schema.
fn variant_tag(variant: &Value) -> &str {
    let tag = &variant["properties"]["type"];
    tag["const"]
        .as_str()
        .or_else(|| tag["enum"][0].as_str())
        .unwrap_or_else(|| panic!("variant without a type tag: {variant}"))
}

fn main() {
    let cfg = Config::new().with_large_int("number");

    let mut v = Decls {
        cfg: &cfg,
        seen: vec![TypeId::of::<Ctrl>()],
        decls: BTreeMap::new(),
    };
    v.decls.insert(Ctrl::ident(&cfg), Ctrl::decl(&cfg));
    Ctrl::visit_dependencies(&mut v);

    let schema = serde_json::to_value(schemars::schema_for!(Ctrl)).unwrap();
    let defs = &schema["$defs"];
    let variants = schema["oneOf"].as_array().expect("Ctrl is a oneOf");
    let mut tags = Vec::new();
    let mut secrets = Vec::new();
    for variant in variants {
        let tag = variant_tag(variant);
        let mut paths = Vec::new();
        secret_paths(variant, defs, &mut Vec::new(), &mut paths, 0);
        // The tag itself is a plain string, never a secret.
        tags.push(tag.to_string());
        if !paths.is_empty() {
            paths.sort();
            secrets.push((tag.to_string(), paths));
        }
    }

    let mut out = String::new();
    out.push_str(
        "// GENERATED by crates/enzarb-proto/examples/gen_ts.rs from the Rust CTRL types. Do not edit.\n\
         // Regenerate with `mise run proto:gen`; CI fails when this file is stale.\n\n\
         import type { SecretLike } from \"./secret.js\";\n\n",
    );
    for decl in v.decls.values() {
        writeln!(out, "export {decl}\n").unwrap();
    }
    out.push_str("/** The `type` tag of every `Ctrl` message, in declaration order. */\n");
    out.push_str("export const CTRL_TYPES = [\n");
    for t in &tags {
        writeln!(out, "  {},", Value::String(t.clone())).unwrap();
    }
    out.push_str("] as const;\n\n");
    out.push_str(
        "/**\n * Secret fields per message `type`, as paths from the message root; `*` stands for any\n * map value or array item. Incoming values at these paths are wrapped in `Secret`.\n */\n",
    );
    out.push_str(
        "export const SECRET_PATHS: Readonly<Record<string, readonly (readonly string[])[]>> = {\n",
    );
    for (tag, paths) in &secrets {
        writeln!(out, "  {tag}: {},", serde_json::to_string(paths).unwrap()).unwrap();
    }
    out.push_str("};\n");

    let target = std::env::args()
        .nth(1)
        .unwrap_or_else(|| DEFAULT_OUT.into());
    if target == "-" {
        print!("{out}");
    } else {
        std::fs::write(&target, out).unwrap_or_else(|e| panic!("write {target}: {e}"));
    }
}
